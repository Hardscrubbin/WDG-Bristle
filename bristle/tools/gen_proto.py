"""Generate Bristle protocol files from spec/bristle_proto.yaml.

    python -I tools/gen_proto.py            regenerate everything and check every test vector
    python -I tools/gen_proto.py --check    fail (exit 1) if any generated file is stale
    python -I tools/gen_proto.py --pin      fill in "TBD" test vectors from the reference code
                                            (use once when adding a vector, then review the diff)

Outputs:
    core/bristle/proto.py                   Python constants (core side)
    firmware/bristle_node/BristleProto.h    C++ constants (node side)
    tests/vectors/vectors.json              test vectors for both sides

Optional: --wdg <path to WDG plugins/_bristle> also copies proto.py there.
"""
from __future__ import annotations

import argparse
import importlib
import json
import pathlib
import re
import sys

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is needed: pip install pyyaml")

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "bristle_proto.yaml"
OUT_PY = ROOT / "core" / "bristle" / "proto.py"
OUT_H = ROOT / "firmware" / "bristle_node" / "BristleProto.h"
OUT_VEC = ROOT / "tests" / "vectors" / "vectors.json"

HEADER_NOTE = "GENERATED by tools/gen_proto.py from spec/bristle_proto.yaml. DO NOT EDIT."


def const_name(s: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", s.upper())


def queue_constants(spec: dict) -> list[tuple[str, int]]:
    """The node queue limits as (NAME, value): QUEUE_* and, for the flash layout, FLASH_*."""
    out = []
    for k, v in spec["queue"].items():
        if isinstance(v, dict):
            out += [(f"FLASH_{const_name(kk)}", vv) for kk, vv in v.items()]
        else:
            out.append((f"QUEUE_{const_name(k)}", v))
    return out


# ------------------------------------------------------------------------------------- python
def gen_python(spec: dict) -> str:
    p, t = spec["product"], spec["timing"]
    a, f, pl = spec["auth"], spec["espnow_frame"], spec["plan"]
    L = [f'"""{HEADER_NOTE}"""', "# fmt: off", ""]
    L += [f'PRODUCT_NAME = {p["name"]!r}', f'NAME_PREFIX = {p["prefix"]!r}',
          f'PROTOCOL_VERSION = {p["protocol_version"]}', ""]
    L += [f'LINE_MAX_BYTES = {spec["line"]["max_bytes"]}', ""]
    L += [f'FRAME_MAGIC = {f["magic"]!r}', f'FRAME_HEADER_BYTES = {f["header_bytes"]}',
          f'FRAME_TAG_BYTES = {f["tag_bytes"]}', f'FRAME_MAX_BYTES = {f["max_bytes"]}',
          f'FRAME_HMAC_LABEL = {f["hmac_label"]!r}']
    for k, v in f["kinds"].items():
        L.append(f"FRAME_KIND_{const_name(k)} = {v}")
    L.append("")
    L += [f'AUTH_KEY_BYTES = {a["key_bytes"]}', f'AUTH_NONCE_BYTES = {a["nonce_bytes"]}',
          f'AUTH_PROOF_BYTES = {a["proof_bytes"]}', f'AUTH_OWNER_ID_BYTES = {a["owner_id_bytes"]}',
          f'AUTH_TIMEOUT_MS = {a["auth_timeout_ms"]}']
    for k, v in a["labels"].items():
        L.append(f"LABEL_{const_name(k)} = {v!r}")
    L.append("")
    ad = spec["adoption"]
    L += [f'ADOPT_TRANSPORTS = {tuple(ad["transports"])!r}', f'FORGET_HOLD_MS = {ad["forget_hold_ms"]}', ""]
    for k, v in pl["flags"].items():
        L.append(f"PLAN_FLAG_{const_name(k)} = {v}")
    L += [f'PLAN_MAX_ENTRIES = {pl["max_entries"]}', f'DWELL_MIN_MS = {pl["dwell_ms"]["min"]}',
          f'DWELL_MAX_MS = {pl["dwell_ms"]["max"]}', f'DWELL_DEFAULT_MS = {pl["dwell_ms"]["default"]}']
    L.append(f"REGIONS = {json.dumps(pl['regions'])}")
    L.append("")
    L.append(f"SECURITY = {json.dumps(spec['security'])}")
    L.append("SECURITY_NAMES = {v: k for k, v in SECURITY.items()}")
    for k, v in spec["link_types"].items():
        L.append(f"LINK_{const_name(k)} = {v}")
    for k, v in spec["heartbeat_flags"].items():
        L.append(f"HB_{const_name(k)} = {v}")
    for k, v in spec["run_mask"].items():
        L.append(f"RUN_{const_name(k)} = {v}")
    L.append("")
    for k, v in t.items():
        L.append(f"{const_name(k)} = {v}")
    for name, value in queue_constants(spec):
        L.append(f"{name} = {value}")
    L.append(f'USB_BAUD = {spec["usb"]["baud"]}')
    b = spec["ble"]
    L += [f'BLE_SERVICE_UUID = {b["service_uuid"]!r}', f'BLE_COMMAND_UUID = {b["command_uuid"]!r}',
          f'BLE_NOTIFY_UUID = {b["notify_uuid"]!r}', f'BLE_MTU = {b["mtu"]}', ""]
    msgs = {k: {"dir": v["dir"], "req": list(v.get("req", [])), "opt": list(v.get("opt", []))}
            for k, v in spec["messages"].items()}
    L.append(f"MESSAGES = {json.dumps(msgs)}")
    L.append(f"ERRORS = {json.dumps(spec['errors'])}")
    L.append("# fmt: on")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------------------------- C++
def gen_header(spec: dict, vectors: dict) -> str:
    p, t = spec["product"], spec["timing"]
    a, f, pl = spec["auth"], spec["espnow_frame"], spec["plan"]
    L = [f"// {HEADER_NOTE}", "#pragma once", "#include <stdint.h>", "", "namespace bp {", ""]
    L += [f'constexpr const char* PRODUCT_NAME = "{p["name"]}";',
          f'constexpr const char* NAME_PREFIX = "{p["prefix"]}";',
          f'constexpr uint8_t PROTOCOL_VERSION = {p["protocol_version"]};',
          f'constexpr uint16_t LINE_MAX_BYTES = {spec["line"]["max_bytes"]};', ""]
    L += [f'constexpr char FRAME_MAGIC0 = \'{f["magic"][0]}\';', f'constexpr char FRAME_MAGIC1 = \'{f["magic"][1]}\';',
          f'constexpr uint8_t FRAME_HEADER_BYTES = {f["header_bytes"]};',
          f'constexpr uint8_t FRAME_TAG_BYTES = {f["tag_bytes"]};',
          f'constexpr uint8_t FRAME_MAX_BYTES = {f["max_bytes"]};',
          f'constexpr const char* FRAME_HMAC_LABEL = "{f["hmac_label"]}";']
    for k, v in f["kinds"].items():
        L.append(f"constexpr uint8_t FRAME_KIND_{const_name(k)} = {v};")
    L.append("")
    L += [f'constexpr uint8_t AUTH_KEY_BYTES = {a["key_bytes"]};',
          f'constexpr uint8_t AUTH_NONCE_BYTES = {a["nonce_bytes"]};',
          f'constexpr uint8_t AUTH_PROOF_BYTES = {a["proof_bytes"]};',
          f'constexpr uint8_t AUTH_OWNER_ID_BYTES = {a["owner_id_bytes"]};',
          f'constexpr uint32_t AUTH_TIMEOUT_MS = {a["auth_timeout_ms"]};']
    for k, v in a["labels"].items():
        L.append(f'constexpr const char* LABEL_{const_name(k)} = "{v}";')
    L.append(f'constexpr uint32_t FORGET_HOLD_MS = {spec["adoption"]["forget_hold_ms"]};')
    L.append("")
    for k, v in pl["flags"].items():
        L.append(f"constexpr uint8_t PLAN_FLAG_{const_name(k)} = {v};")
    L += [f'constexpr uint8_t PLAN_MAX_ENTRIES = {pl["max_entries"]};',
          f'constexpr uint16_t DWELL_MIN_MS = {pl["dwell_ms"]["min"]};',
          f'constexpr uint16_t DWELL_MAX_MS = {pl["dwell_ms"]["max"]};',
          f'constexpr uint16_t DWELL_DEFAULT_MS = {pl["dwell_ms"]["default"]};']
    for rk, rv in pl["regions"].items():
        for band in ("ch24", "ch5"):
            arr = ", ".join(str(c) for c in rv[band])
            L.append(f"constexpr uint8_t REGION_{rk}_{band.upper()}[] = {{{arr}}};")
        L.append(f'constexpr const char* REGION_{rk}_COUNTRY = "{rv["country"]}";')
    L.append("")
    L.append("enum Security : uint8_t {")
    for k, v in spec["security"].items():
        L.append(f"  SEC_{const_name(k)} = {v},")
    L.append("};")
    for k, v in spec["link_types"].items():
        L.append(f"constexpr uint8_t LINK_{const_name(k)} = {v};")
    for k, v in spec["heartbeat_flags"].items():
        L.append(f"constexpr uint16_t HB_{const_name(k)} = {v};")
    for k, v in spec["run_mask"].items():
        L.append(f"constexpr uint8_t RUN_{const_name(k)} = {v};")
    L.append("")
    for k, v in t.items():
        L.append(f"constexpr uint32_t {const_name(k)} = {v};")
    for name, value in queue_constants(spec):
        L.append(f"constexpr uint32_t {name} = {value};")
    L.append(f'constexpr uint32_t USB_BAUD = {spec["usb"]["baud"]};')
    b = spec["ble"]
    L += [f'constexpr const char* BLE_SERVICE_UUID = "{b["service_uuid"]}";',
          f'constexpr const char* BLE_COMMAND_UUID = "{b["command_uuid"]}";',
          f'constexpr const char* BLE_NOTIFY_UUID = "{b["notify_uuid"]}";',
          f'constexpr uint16_t BLE_MTU = {b["mtu"]};', ""]
    for k in spec["messages"]:
        L.append(f'constexpr const char* MSG_{k} = "{k}";')
    L.append("")
    for k, v in spec["errors"].items():
        L.append(f'constexpr const char* ERR_{k} = "{v}";')
    L.append("")
    L.append("// Test vectors (checked by the node's `selftest` console command)")
    for name, items in vectors.items():
        for i, v in enumerate(items):
            for kk, vv in v.items():
                cname = f"VEC_{const_name(name)}_{i}_{const_name(kk)}"
                if isinstance(vv, int):
                    L.append(f"constexpr long {cname} = {vv};")
                else:
                    L.append(f'constexpr const char* {cname} = "{vv}";')
    L += ["", "}  // namespace bp", ""]
    return "\n".join(L)


# ------------------------------------------------------------------------------------- vectors
def compute_vectors(spec: dict) -> dict:
    sys.path.insert(0, str(ROOT / "core"))
    for m in ("bristle.proto", "bristle.codec", "bristle.crypto", "bristle.plan"):
        if m in sys.modules:
            importlib.reload(sys.modules[m])
    from bristle import codec, crypto, plan  # noqa: E402

    out: dict[str, list] = {}
    vec = spec["vectors"]
    out["crc16"] = [{**v, "got": f"{codec.crc16(v['input'].encode()):04X}"} for v in vec["crc16"]]
    out["encode"] = [{**v, "got": codec.pct_encode(v["input"])} for v in vec["encode"]]
    out["plan_hash"] = [{**v, "got": plan.Plan.from_fields(str(v["f"]), v["r"], v["c"],
                                                         str(v["d"]) if "d" in v else None).hash()}
                        for v in vec["plan_hash"]]
    out["owner_id"] = [{**v, "got": crypto.owner_id(bytes.fromhex(v["key"]))} for v in vec["owner_id"]]
    out["node_proof"] = [{**v, "got": crypto.node_proof(bytes.fromhex(v["key"]), bytes.fromhex(v["cn"]),
                                                       bytes.fromhex(v["hw"]))} for v in vec["node_proof"]]
    out["core_proof"] = [{**v, "got": crypto.core_proof(bytes.fromhex(v["key"]), bytes.fromhex(v["nn"]),
                                                       bytes.fromhex(v["hw"]))} for v in vec["core_proof"]]
    out["frame"] = [{**v, "got": crypto.frame_build(bytes.fromhex(v["key"]), v["kind"], v["ctr"], v["frag"],
                                                    v["payload"].encode()).hex()} for v in vec["frame"]]
    return out


def pin_vectors(text: str, computed: dict) -> str:
    """Replace each vector's expect value in the YAML text, in order, keeping comments."""
    vec_start = text.index("\nvectors:")
    head, tail = text[:vec_start], text[vec_start:]
    flat = [v["got"] for name in ("crc16", "encode", "plan_hash", "owner_id", "node_proof",
                                  "core_proof", "frame") for v in computed[name]]
    it = iter(flat)

    def repl(m: re.Match) -> str:
        return f'expect: "{next(it)}"'

    tail = re.sub(r'expect: "[^"]*"', repl, tail)
    return head + tail


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--pin", action="store_true")
    ap.add_argument("--wdg", type=pathlib.Path)
    args = ap.parse_args()

    text = SPEC.read_text(encoding="utf-8")
    spec = yaml.safe_load(text)

    py = gen_python(spec)
    if not args.check:
        OUT_PY.parent.mkdir(parents=True, exist_ok=True)
        OUT_PY.write_text(py, encoding="utf-8", newline="\n")

    computed = compute_vectors(spec)
    bad = [(n, v) for n, items in computed.items() for v in items if v["expect"] != v["got"]]
    if bad and args.pin:
        text = pin_vectors(text, computed)
        SPEC.write_text(text, encoding="utf-8", newline="\n")
        spec = yaml.safe_load(text)
        computed = compute_vectors(spec)
        bad = [(n, v) for n, items in computed.items() for v in items if v["expect"] != v["got"]]
        print("pinned test vectors into the spec; review the diff")
    if bad:
        for n, v in bad:
            print(f"VECTOR MISMATCH {n}: expect {v['expect']} got {v['got']}")
        return 1

    vectors = {n: [{k: v for k, v in item.items() if k != "got"} for item in items]
               for n, items in computed.items()}
    hdr = gen_header(spec, vectors)
    vec_json = json.dumps(vectors, indent=2) + "\n"

    outputs = {OUT_PY: py, OUT_H: hdr, OUT_VEC: vec_json}
    if args.check:
        stale = [p for p, content in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != content]
        for p in stale:
            print(f"STALE: {p.relative_to(ROOT)}  (run tools/gen_proto.py)")
        return 1 if stale else 0

    for p, content in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    if args.wdg:
        dst = args.wdg / "proto.py"
        dst.write_text(py, encoding="utf-8", newline="\n")
        print(f"copied proto.py to {dst}")
    print(f"all {sum(len(v) for v in vectors.values())} test vectors pass")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
